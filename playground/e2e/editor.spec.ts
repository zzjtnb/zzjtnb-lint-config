import { expect, test } from '@playwright/test'
import { replaceEditor } from './helpers'

test('Monaco 编辑配置与代码，诊断和 Console 同屏及主题同步', async ({ page }) => {
  await page.goto('/#/eslint/experiment')
  const source = page.locator('.source-panel .monaco-diff-editor .original .view-lines')
  await expect(source).toBeVisible({ timeout: 90000 })
  await replaceEditor(page, source, 'const editorTest = 1\n')
  await expect(source).toContainText('editorTest')
  await expect(page.locator('.console-panel .xterm-screen')).toBeVisible()
  await expect(page.locator('.diagnostics')).toBeVisible()
  await page.getByRole('tab', { name: '配置源码', exact: true }).click()
  const configuration = page.locator('.source-config .monaco-editor .view-lines')
  await expect(configuration).toBeVisible({ timeout: 90000 })
  await replaceEditor(page, configuration, 'export default [{ rules: {} }]')
  await expect(configuration).toContainText('export default [{ rules: {} }]')
  const background = await page.locator('.source-panel .monaco-editor').first().evaluate(element => getComputedStyle(element).backgroundColor)
  await page.getByRole('button', { name: '切换深色', exact: true }).click()
  await expect.poll(() => page.locator('.source-panel .monaco-editor').first().evaluate(element => getComputedStyle(element).backgroundColor)).not.toBe(background)
  await page.screenshot({ path: '../.tmp/playground/validation/editor/console.png', fullPage: true })
  await page.getByRole('link', { name: '项目接入', exact: true }).click()
  await expect(page.locator('#save pre')).toContainText('rules: {}')
  await page.goBack()
  await expect(page.locator('.source-panel .original .view-lines')).toContainText('editorTest', { timeout: 90000 })
  await page.setViewportSize({ width: 390, height: 844 })
  const mobileSource = page.locator('.source-panel .original .view-lines')
  await replaceEditor(page, mobileSource, 'const mobileEdit = 2\n')
  await expect(mobileSource).toContainText('mobileEdit')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
