import { expect, test } from '@playwright/test'
import { chooseOption, replaceEditor } from './helpers'

test('执行中取消保留源码与配置，修正配置后重新启动服务', async ({ page }) => {
  test.setTimeout(480000)
  await page.goto('/#/eslint/overview')
  await page.getByRole('link', { name: 'Markdownlint', exact: true }).click()
  await page.getByRole('link', { name: '代码实验', exact: true }).click()
  await expect(page.locator('.runtime-state')).toContainText('浏览器引擎已就绪', { timeout: 360000 })
  await page.getByRole('tab', { name: '配置源码', exact: true }).click()
  const configuration = page.locator('.source-config .view-lines')
  await expect(configuration).toBeVisible({ timeout: 90000 })
  await replaceEditor(page, configuration, 'export default new Promise(() => {})')
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(page.getByRole('button', { name: '取消执行', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '取消执行', exact: true }).click({ timeout: 5000 })
  await expect(page.getByRole('button', { name: '检查代码', exact: true })).toBeEnabled()
  await expect(page.locator('.diagnostics .notice.error')).toContainText('操作已取消')
  await expect(page.locator('.runtime-state')).toContainText('检查已取消')
  await expect(configuration).toContainText('new Promise')
  await replaceEditor(page, configuration, 'export default { default: false, MD009: true }')
  await page.getByRole('button', { name: '检查代码', exact: true }).click()
  await expect(page.getByRole('button', { name: '检查代码', exact: true })).toBeEnabled({ timeout: 30000 })
  await expect(page.locator('.diagnostics .notice.error')).toHaveCount(0)
  await expect(page.locator('.diagnostic').first()).toBeVisible()
  await chooseOption(page, page.getByRole('combobox', { name: '编辑文件', exact: true }), '__custom__')
  const filename = page.getByRole('textbox', { name: '编辑文件', exact: true })
  const original = await filename.inputValue()
  await filename.fill('unsupported.txt')
  await page.getByRole('button', { name: '检查代码', exact: true }).click()
  await expect(page.locator('.diagnostics .notice.error')).toContainText('当前工具不支持此文件类型', { timeout: 10000 })
  await filename.fill(original)
  await page.getByRole('button', { name: '检查代码', exact: true }).click()
  await expect(page.getByRole('button', { name: '检查代码', exact: true })).toBeEnabled({ timeout: 30000 })
  await expect(page.locator('.diagnostics .notice.error')).toHaveCount(0)
})
