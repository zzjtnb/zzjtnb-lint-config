import { expect, test } from '@playwright/test'

test('配置路径使用可搜索候选，选择及自由输入均自动解析真实配置', async ({ page }) => {
  test.setTimeout(480000)
  await page.goto('/#/markdownlint/overview')
  const path = page.getByRole('combobox', { name: '测试配置匹配路径' })
  await path.click()
  await path.fill('doc')
  await expect(page.getByText('选择候选文件，或继续输入带扩展名的完整路径后自动匹配。')).toBeVisible()
  const popup = page.locator('.file-autocomplete-content')
  await expect(popup).toBeVisible()
  const formBox = (await page.locator('.matching-form').boundingBox())!
  expect((await path.boundingBox())!.width).toBeGreaterThan(formBox.width * 0.75)
  expect(await popup.evaluate(element => getComputedStyle(element).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
  await expect(page.getByRole('option', { name: 'document.md', exact: true })).toBeVisible()
  await page.getByRole('option', { name: 'document.md', exact: true }).click()
  await expect(page.locator('.matching-result')).toContainText('最终合并', { timeout: 420000 })
  await page.getByRole('tab', { name: '最终合并规则', exact: true }).click()
  await expect(page.getByRole('tabpanel')).toContainText('当前文件最终合并规则')
  await path.fill('docs/example.md')
  await path.press('Tab')
  await expect(page.locator('.matching-result')).toContainText('docs/example.md', { timeout: 70000 })
  await page.getByRole('button', { name: '清除文件路径' }).click()
  await expect(path).toHaveValue('')
  await expect(page.locator('.matching-result')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: '最终合并规则', exact: true })).toHaveCount(0)
  await path.click()
  await expect(page.getByRole('option', { name: 'document.md', exact: true })).toBeVisible()
  await path.press('Escape')
  await page.getByRole('link', { name: '规则目录', exact: true }).click()
  const search = page.getByRole('searchbox', { name: '搜索规则名称或说明' })
  await search.focus()
  expect(await search.evaluate(element => getComputedStyle(element).outlineStyle)).toBe('none')
})

test('输入未完成文件名只过滤候选，不执行不支持的文件匹配', async ({ page }) => {
  await page.route('**/runtime/*.json', route => route.fulfill({ status: 503, body: '此用例只验证输入行为' }))
  await page.goto('/#/eslint/overview')
  const path = page.getByRole('combobox', { name: '测试配置匹配路径' })
  await path.fill('component')
  await expect(page.getByRole('option', { name: 'component.vue', exact: true })).toBeVisible()
  await expect(page.getByText('选择候选文件，或继续输入带扩展名的完整路径后自动匹配。')).toBeVisible()
  await expect(page.locator('.matching-result')).toHaveCount(0)
  await expect(page.locator('.notice.error')).toHaveCount(0)
  const form = (await page.locator('.matching-form').boundingBox())!
  expect((await path.boundingBox())!.width).toBeGreaterThan(form.width * 0.75)
  await page.screenshot({ path: '../.tmp/ui-matching/fragment-verified.png', fullPage: true })
})
